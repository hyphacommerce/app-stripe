// Bundles the browser modules (the storefront element, the settings page's script) with
// esbuild and writes them into src/generated/assets.ts as strings, so Workers and Node
// serve the same bytes with no static-file setup. With --check, fails instead of
// writing when the committed file is out of date (CI runs it).

import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";

import { build } from "esbuild";

const target = new URL("../src/generated/assets.ts", import.meta.url);
const check = process.argv.includes("--check");

const entries = {
  paymentElement: "src/browser/payment-element.ts",
  settingsScript: "src/browser/settings.ts",
} as const;

async function bundle(entry: string): Promise<string> {
  const result = await build({
    entryPoints: [new URL(`../${entry}`, import.meta.url).pathname],
    bundle: true,
    format: "esm",
    target: "es2022",
    platform: "browser",
    minify: true,
    legalComments: "none",
    write: false,
    charset: "utf8",
  });
  const file = result.outputFiles[0];
  if (!file) throw new Error(`esbuild wrote nothing for ${entry}`);
  return file.text;
}

let out = `// Generated by scripts/build-assets.ts from src/browser/. Don't edit: run \`pnpm build\`.\n\n`;
for (const [name, entry] of Object.entries(entries)) {
  const code = await bundle(entry);
  const hash = createHash("sha256").update(code).digest("hex").slice(0, 16);
  out += `export const ${name} = { hash: ${JSON.stringify(hash)}, code: ${JSON.stringify(code)} };\n`;
}

if (check) {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== out) {
    console.error("src/generated/assets.ts is out of date: run `pnpm build` and commit it.");
    process.exit(1);
  }
  console.log("src/generated/assets.ts is up to date.");
} else {
  await writeFile(target, out);
  console.log("wrote src/generated/assets.ts");
}
